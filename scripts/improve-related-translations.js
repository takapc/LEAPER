const words = JSON.parse(await readFile(wordsUrl, 'utf8'))
let updatedCount = 0
const matchedOverrides = new Set()

for (const word of words) {
  for (const relatedWord of word.relatedWords ?? []) {
    const key = `${word.word.toLowerCase()}>${relatedWord.word.toLowerCase()}`
    const improvedMeaning = meaningOverrides[key]

    if (improvedMeaning) {
      matchedOverrides.add(key)
      if (improvedMeaning !== relatedWord.meaning) {
        relatedWord.meaning = improvedMeaning
        updatedCount += 1
      }
    }
  }
}

const missingOverrides = Object.keys(meaningOverrides).filter((key) => !matchedOverrides.has(key))
if (missingOverrides.length > 0) {
  throw new Error(`Related-word overrides no longer present in words.json: ${missingOverrides.join(', ')}`)
}

await writeFile(wordsUrl, `${JSON.stringify(words, null, 2)}\n`)
console.log(`Updated ${updatedCount} related-word translations.`)
